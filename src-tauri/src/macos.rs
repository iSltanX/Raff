/// True when the caller is already on the AppKit main thread.
///
/// `MainThreadMarker::new()` is `Some` only on the main thread, which is
/// exactly the question, and it costs one `NSThread.isMainThread` check.
pub fn is_main_thread() -> bool {
    MainThreadMarker::new().is_some()
}

/// Queues `work` onto the main thread via libdispatch, without blocking.
///
/// This deliberately does NOT go through `AppHandle::run_on_main_thread`.
/// That posts to tao's event-loop proxy, and tao only drains that queue while
/// it is processing events — but Raff is an accessory (`LSUIElement`) app that
/// sits with no visible window most of the time, so its loop is parked and
/// nothing drains. Measured on a cold launch, a panel-show posted that way
/// took 2.5 SECONDS to run, and sometimes did not run at all until an
/// unrelated event happened along. Waking CFRunLoop first does not help: the
/// loop wakes, but tao still is not iterating, so its queue stays untouched.
///
/// libdispatch's main queue is drained by AppKit's own run-loop integration,
/// which is always installed, so work lands on the next turn regardless of
/// what tao is doing. `exec_async` (not `exec_sync`/`run_on_main`, which
/// block and could deadlock against a caller already holding a lock the main
/// thread wants) keeps the calling thread free.
pub fn dispatch_to_main<F: FnOnce() + Send + 'static>(work: F) {
    dispatch2::DispatchQueue::main().exec_async(work);
}

/// nspasteboard.org's «do not record» markers. Password managers set
/// Concealed; generated values set AutoGenerated; apps set Transient on their
/// own momentary writes (a text expander, a converter restoring the clipboard).
/// Content carrying any of them is never stored.
const CONCEALED_TYPES: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
    "org.nspasteboard.TransientType",
];

const TYPE_TEXT: &str = "public.utf8-plain-text";
const TYPE_HTML: &str = "public.html";
const TYPE_RTF: &str = "public.rtf";
const TYPE_PNG: &str = "public.png";
const TYPE_TIFF: &str = "public.tiff";
const TYPE_JPEG: &str = "public.jpeg";
const TYPE_FILE_URL: &str = "public.file-url";

/// Rich representations larger than this are not stored (keeps the JSON store lean).
const MAX_RICH_BYTES: usize = 256 * 1024;
/// Image payloads above this are not read into the process at all. An
/// uncompressed TIFF of a 6K screen is ~81 MB, so a full-screen Retina capture
/// still fits; the cap exists so the worst case has a number.
const MAX_IMAGE_BYTES: usize = 96 * 1024 * 1024;
/// Plain text longer than this is not captured. `history.json` is rewritten in
/// full on every capture, so one oversized item is a tax on every capture after
/// it — not just on the one that stored it.
pub const MAX_TEXT_CHARS: usize = 100_000;
/// A char is at most four UTF-8 bytes, so nothing inside `MAX_TEXT_CHARS` is
/// ever rejected here. This only avoids materialising a string that could not
/// pass the char cap anyway.
const MAX_TEXT_BYTES: usize = MAX_TEXT_CHARS * 4;

/// Raw pasteboard content, as captured. `rtf`/`html` are kept so a normal paste
/// can restore formatting while "paste as plain text" writes only `text`.
#[derive(Default)]
pub struct RawClip {
    pub text: Option<String>,
    pub html: Option<String>,
    pub rtf: Option<Vec<u8>>,
    pub png: Option<Vec<u8>>,
    pub tiff: Option<Vec<u8>>,
}

#[derive(Clone, Debug, Default)]
pub struct FrontApp {
    pub pid: i32,
    pub name: String,
    pub bundle_id: String,
}

/// Whether this process may touch the system clipboard at all (ت٤٨).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Clipboard {
    Real,
    /// Never read, never written, no ⌘V sent: a test run of رفّ.
    Inert,
}

/// Decided from what the process was launched as, never from its settings
/// or anything after launch (ت٤٨). A test run of رفّ — isolated beside the
/// installed one, or a probe build under its own `com.raff.app.*` identity —
/// has an inert clipboard: the installed رفّ already records the real one,
/// and a test must not read, overwrite or paste from the user's. The
/// identity holds however the probe is opened (Finder, `open`, a relaunch),
/// where an environment variable would not.
pub fn clipboard_for(isolated: bool, bundle_id: Option<&str>) -> Clipboard {
    let probe = bundle_id.is_some_and(|id| id.starts_with("com.raff.app."));
    if isolated || probe {
        Clipboard::Inert
    } else {
        Clipboard::Real
    }
}

/// Whether this is a test run of رفّ, with no clipboard (ت٤٨).
pub fn clipboard_inert() -> bool {
    clipboard() == Clipboard::Inert
}

/// Decides, once and before anything can reach the pasteboard, whether this
/// process may touch the clipboard. `main` calls it first; any earlier reach
/// would decide it the same way.
pub fn decide_clipboard() -> Clipboard {
    clipboard()
}

fn clipboard() -> Clipboard {
    #[cfg(test)]
    if let Some(policy) = test_clipboard::policy() {
        return policy;
    }
    static DECIDED: OnceLock<Clipboard> = OnceLock::new();
    *DECIDED.get_or_init(|| {
        let bundle = objc2_foundation::NSBundle::mainBundle()
            .bundleIdentifier()
            .map(|id| id.to_string());
        clipboard_for(crate::dev_isolated(), bundle.as_deref())
    })
}

/// The one way to the system pasteboard, and the gate on it.
fn general_pasteboard() -> Option<Retained<NSPasteboard>> {
    if clipboard() == Clipboard::Inert {
        return None;
    }
    system_pasteboard()
}

#[cfg(not(test))]
fn system_pasteboard() -> Option<Retained<NSPasteboard>> {
    Some(NSPasteboard::generalPasteboard())
}

/// Tests can only ever reach a private pasteboard the test made, never the
/// user's clipboard.
#[cfg(test)]
fn system_pasteboard() -> Option<Retained<NSPasteboard>> {
    test_clipboard::pasteboard()
}

/// Tests only: a private pasteboard per test, a count of every time the
/// code reached for a pasteboard, and of every ⌘V it would have sent.
#[cfg(test)]
pub(crate) mod test_clipboard {
    use super::Clipboard;
    use objc2::rc::Retained;
    use objc2_app_kit::NSPasteboard;
    use std::cell::{Cell, RefCell};

    thread_local! {
        static AFTER_WRITE: RefCell<Option<Box<dyn FnOnce()>>> = const { RefCell::new(None) };
        static POLICY: Cell<Option<Clipboard>> = const { Cell::new(None) };
        static PASTEBOARD: RefCell<Option<Retained<NSPasteboard>>> = const { RefCell::new(None) };
        static TOUCHES: Cell<usize> = const { Cell::new(0) };
        static CMD_V: Cell<usize> = const { Cell::new(0) };
    }

    pub(crate) fn policy() -> Option<Clipboard> {
        POLICY.get()
    }

    pub(crate) fn pasteboard() -> Option<Retained<NSPasteboard>> {
        TOUCHES.set(TOUCHES.get() + 1);
        PASTEBOARD.with_borrow(Clone::clone)
    }

    /// Runs `f` inside the next `write_clip`, after its representations are
    /// set and before it returns: another app writing at that moment.
    pub(crate) fn after_write(f: impl FnOnce() + 'static) {
        AFTER_WRITE.set(Some(Box::new(f)));
    }

    pub(crate) fn run_after_write() {
        if let Some(f) = AFTER_WRITE.take() {
            f();
        }
    }

    pub(crate) fn note_cmd_v() {
        CMD_V.set(CMD_V.get() + 1);
    }

    /// Runs `body` as a process under `policy`, with a private pasteboard
    /// made for it and released after. Returns what it touched: pasteboard
    /// reaches and ⌘V presses.
    pub(crate) fn run(policy: Clipboard, body: impl FnOnce()) -> (usize, usize) {
        let private = NSPasteboard::pasteboardWithUniqueName();
        POLICY.set(Some(policy));
        PASTEBOARD.set(Some(private.clone()));
        TOUCHES.set(0);
        CMD_V.set(0);
        body();
        let touched = (TOUCHES.get(), CMD_V.get());
        POLICY.set(None);
        PASTEBOARD.set(None);
        // SAFETY: `releaseGlobally` takes no arguments and returns nothing; the
        // binding crate does not generate it.
        let _: () = unsafe { objc2::msg_send![&*private, releaseGlobally] };
        touched
    }
}

pub fn change_count() -> isize {
    general_pasteboard().map_or(0, |pb| pb.changeCount())
}

pub fn has_concealed_type() -> bool {
    let Some(pb) = general_pasteboard() else {
        return false;
    };
    let Some(types) = pb.types() else {
        return false;
    };
    types
        .iter()
        .any(|t| CONCEALED_TYPES.contains(&t.to_string().as_str()))
}

pub fn read_clip() -> RawClip {
    let Some(pb) = general_pasteboard() else {
        return RawClip::default();
    };
    // Every representation is measured on the pasteboard's own object and only
    // then copied, so an oversized payload never enters this process.
    let capped_string_for = |t: &str, max: usize| {
        pb.stringForType(&NSString::from_str(t))
            .filter(|s| s.len() <= max)
            .map(|s| s.to_string())
    };
    let capped_data_for = |t: &str, max: usize| {
        pb.dataForType(&NSString::from_str(t))
            .filter(|d| {
                let len = d.len();
                len > 0 && len <= max
            })
            .map(|d| d.to_vec())
    };

    let text = capped_string_for(TYPE_TEXT, MAX_TEXT_BYTES)
        .filter(|t| t.chars().count() <= MAX_TEXT_CHARS);
    let html = capped_string_for(TYPE_HTML, MAX_RICH_BYTES);
    let rtf = capped_data_for(TYPE_RTF, MAX_RICH_BYTES);
    // Only bother with image data when there is no text representation.
    let (png, tiff) = if text.as_deref().map(|t| !t.trim().is_empty()) == Some(true) {
        (None, None)
    } else {
        (
            capped_data_for(TYPE_PNG, MAX_IMAGE_BYTES),
            capped_data_for(TYPE_TIFF, MAX_IMAGE_BYTES),
        )
    };

    RawClip {
        text,
        html,
        rtf,
        png,
        tiff,
    }
}

/// Writes the given representations to the general pasteboard and returns the
/// change count only when at least one requested representation was accepted
/// (so callers never report copy/paste success for a rejected write).
///
/// The count is the one `clearContents` produced, not one read afterwards:
/// setting representations does not move it, so a count read after the last
/// one would name another app's write landing in between as رفّ's, and that
/// copy would never be captured.
pub fn write_clip(
    text: Option<&str>,
    html: Option<&str>,
    rtf: Option<&[u8]>,
    png: Option<&[u8]>,
) -> Option<isize> {
    let pb = general_pasteboard()?;
    let cleared = pb.clearContents();
    let mut accepted = false;
    if let Some(t) = text {
        accepted |= pb.setString_forType(&NSString::from_str(t), &NSString::from_str(TYPE_TEXT));
    }
    if let Some(h) = html {
        accepted |= pb.setString_forType(&NSString::from_str(h), &NSString::from_str(TYPE_HTML));
    }
    if let Some(r) = rtf {
        accepted |= pb.setData_forType(Some(&NSData::with_bytes(r)), &NSString::from_str(TYPE_RTF));
    }
    if let Some(p) = png {
        accepted |= pb.setData_forType(Some(&NSData::with_bytes(p)), &NSString::from_str(TYPE_PNG));
    }
    #[cfg(test)]
    test_clipboard::run_after_write();
    accepted.then_some(cleared)
}

/// «اختر صورة…» in the report window: a native open panel limited to the
/// formats a report takes. Main thread only. The path stays in Rust — the
/// webview never learns it, and the report never carries it.
pub fn choose_image_file() -> Option<String> {
    let mtm = MainThreadMarker::new()?;
    let panel = NSOpenPanel::openPanel(mtm);
    panel.setCanChooseFiles(true);
    panel.setCanChooseDirectories(false);
    panel.setAllowsMultipleSelection(false);
    panel.setPrompt(Some(&NSString::from_str("إرفاق")));
    // `allowedContentTypes` takes UTType, a crate رفّ does not ship; the
    // extension list filters the same, and the bytes are sniffed regardless.
    let extensions = ["png", "jpg", "jpeg"].map(NSString::from_str);
    #[allow(deprecated)]
    panel.setAllowedFileTypes(Some(&NSArray::from_retained_slice(&extensions)));
    if panel.runModal() != NSModalResponseOK {
        return None;
    }
    panel.URL()?.path().map(|p| p.to_string())
}


/// What a paste in the report window found on the pasteboard.
pub enum PastedImage {
    Image(Vec<u8>),
    /// A file copied in Finder: its pasteboard image is the file's icon, not
    /// the picture, so it is not attached — «اختر صورة…» picks the file.
    File,
    /// An image, but over the input ceiling (019): said so, rather than «no
    /// image».
    TooLarge,
    Nothing,
}

/// A paste in the report window: the pasteboard's image, read at that moment
/// and for that purpose only. Content an app marked secret is never read.
pub fn read_image_for_report() -> PastedImage {
    if has_concealed_type() {
        return PastedImage::Nothing;
    }
    let Some(pb) = general_pasteboard() else {
        return PastedImage::Nothing;
    };
    let is_file = pb
        .types()
        .is_some_and(|types| types.iter().any(|t| t.to_string() == TYPE_FILE_URL));
    if is_file {
        return PastedImage::File;
    }
    [TYPE_PNG, TYPE_TIFF, TYPE_JPEG]
        .iter()
        .find_map(|t| {
            pb.dataForType(&NSString::from_str(t))
                .filter(|d| !d.is_empty())
        })
        .map_or(PastedImage::Nothing, |d| {
            if d.len() > crate::report_image::MAX_INPUT_BYTES {
                PastedImage::TooLarge
            } else {
                PastedImage::Image(d.to_vec())
            }
        })
}

pub fn frontmost_app() -> FrontApp {
    let ws = NSWorkspace::sharedWorkspace();
    match ws.frontmostApplication() {
        Some(app) => FrontApp {
            pid: app.processIdentifier(),
            name: app
                .localizedName()
                .map(|s| s.to_string())
                .unwrap_or_default(),
            bundle_id: app
                .bundleIdentifier()
                .map(|s| s.to_string())
                .unwrap_or_default(),
        },
        None => FrontApp::default(),
    }
}

/// One frontmost-app change, as NSWorkspace reported it: the app that took the
/// front and the instant it did.
#[derive(Clone, Debug)]
pub struct Activation {
    pub at: Instant,
    pub app: FrontApp,
}

/// The least the log keeps. A capture looks back to the previous poll
/// (`monitor::Watch`), however long ago a held-up poll makes that, and the
/// loop says where its next window opens (`keep_activations_since`): nothing
/// from there on is dropped, whatever its age.
const ACTIVATION_KEEP: Duration = Duration::from_secs(5 * 60);

fn activation_log() -> &'static Mutex<Vec<Activation>> {
    static LOG: OnceLock<Mutex<Vec<Activation>>> = OnceLock::new();
    LOG.get_or_init(|| Mutex::new(Vec::new()))
}

/// Records `app` as owning the front from now on, oldest entry first.
pub fn note_activation(app: FrontApp) {
    let now = Instant::now();
    let mut log = activation_log()
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner());
    let needed = *window_opened().lock().unwrap_or_else(|p| p.into_inner());
    forget_old_activations(&mut log, now, needed);
    remember_front(app.pid, is_regular_app(app.pid));
    log.push(Activation { at: now, app });
}

/// Where the capture loop's next window opens: its last look at the count.
fn window_opened() -> &'static Mutex<Option<Instant>> {
    static OPENED: OnceLock<Mutex<Option<Instant>>> = OnceLock::new();
    OPENED.get_or_init(|| Mutex::new(None))
}

/// Called by the capture loop at every look: nothing from `at` on may be
/// forgotten, however long the next poll is held up.
pub fn keep_activations_since(at: Instant) {
    *window_opened().lock().unwrap_or_else(|p| p.into_inner()) = Some(at);
}

/// Called when the capture loop has given up: no window will ask again, and
/// a mark left standing would keep every later activation for the life of
/// the process.
pub fn stop_keeping_activations() {
    *window_opened().lock().unwrap_or_else(|p| p.into_inner()) = None;
}

/// Drops what no capture will ask about any more. The newest activation at or
/// before the cutoff stays: it is the one still in force, and dropping it
/// would lose the answer for older windows.
fn forget_old_activations(log: &mut Vec<Activation>, now: Instant, needed: Option<Instant>) {
    let by_age = now.checked_sub(ACTIVATION_KEEP).unwrap_or(now);
    let cutoff = needed.map_or(by_age, |opened| opened.min(by_age));
    let keep_from = log.iter().rposition(|a| a.at <= cutoff).unwrap_or(0);
    log.drain(..keep_from);
}

/// The last app other than رفّ to take the front: where the user was (ت٤٧).
/// Kept apart from the activation log, which forgets after five minutes.
static LAST_OTHER_APP: std::sync::atomic::AtomicI32 = std::sync::atomic::AtomicI32::new(0);

/// Whether an app taking the front is one to give it back to later: not رفّ
/// itself, and a regular app — an agent with no windows would leave the
/// keyboard as dead as before.
fn worth_returning_to(pid: i32, own: i32, regular: bool) -> bool {
    pid > 0 && pid != own && regular
}

fn remember_front(pid: i32, regular: bool) {
    if worth_returning_to(pid, std::process::id() as i32, regular) {
        LAST_OTHER_APP.store(pid, std::sync::atomic::Ordering::Release);
    }
}

fn is_regular_app(pid: i32) -> bool {
    use objc2_app_kit::NSApplicationActivationPolicy;
    pid > 0
        && NSRunningApplication::runningApplicationWithProcessIdentifier(pid).is_some_and(|app| {
            !app.isTerminated() && app.activationPolicy() == NSApplicationActivationPolicy::Regular
        })
}

pub fn last_other_app() -> Option<i32> {
    let pid = LAST_OTHER_APP.load(std::sync::atomic::Ordering::Acquire);
    (pid > 0).then_some(pid)
}

/// Whether رفّ is the active app, and whether one of its windows has the
/// key. Main thread; elsewhere it answers "nothing to do".
pub fn app_focus() -> (bool, bool) {
    let Some(mtm) = MainThreadMarker::new() else {
        return (false, true);
    };
    let app = NSApplication::sharedApplication(mtm);
    // SAFETY: `keyWindow` takes no arguments and returns an NSWindow or nil.
    let key: *mut AnyObject = unsafe { msg_send![&*app, keyWindow] };
    (app.isActive(), !key.is_null())
}

/// Gives the front back to the app the user was in before رفّ took it; when
/// that app is gone, رفّ just steps aside and macOS picks the next one.
/// Main thread.
pub fn hand_focus_back() {
    match last_other_app().filter(|pid| is_regular_app(*pid)) {
        Some(pid) => activate_app(pid),
        None => {
            if let Some(mtm) = MainThreadMarker::new() {
                NSApplication::sharedApplication(mtm).deactivate();
            }
        }
    }
}

/// Snapshot of the activation log, oldest first.
pub fn activation_snapshot() -> Vec<Activation> {
    activation_log()
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
        .clone()
}

/// True when any app that held the front during `[at - window, at]` is excluded.
///
/// An activation at `t` means that app owned the front from `t` until the next
/// one, so the window covers the activation in force when it opened plus every
/// activation inside it — not only the newest, which is all `frontmost_app()`
/// can answer, and which is exactly what the copy-then-switch race defeats.
pub fn window_has_excluded(
    log: &[Activation],
    excluded: &[String],
    at: Instant,
    window: Duration,
) -> bool {
    let is_excluded = |a: &Activation| excluded.iter().any(|e| *e == a.app.bundle_id);
    front_when_window_opened(log, at, window).is_some_and(is_excluded)
        || log
            .iter()
            .filter(|a| a.at > window_start(at, window) && a.at <= at)
            .any(is_excluded)
}

/// The app that held the front when the window opened — the best available
/// guess at who owned a copy detected at `at`. `None` when the log does not
/// reach that far back.
pub fn front_at(log: &[Activation], at: Instant, window: Duration) -> Option<FrontApp> {
    front_when_window_opened(log, at, window).map(|a| a.app.clone())
}

fn window_start(at: Instant, window: Duration) -> Instant {
    at.checked_sub(window).unwrap_or(at)
}

/// The newest activation at or before the window opened — the one still in
/// force when it did. `None` when the log does not reach that far back.
fn front_when_window_opened(
    log: &[Activation],
    at: Instant,
    window: Duration,
) -> Option<&Activation> {
    let start = window_start(at, window);
    log.iter().rev().find(|a| a.at <= start)
}

define_class!(
    // SAFETY:
    // - The superclass NSObject has no subclassing requirements.
    // - `ActivationObserver` does not implement `Drop`.
    #[unsafe(super(NSObject))]
    #[name = "RaffActivationObserver"]
    struct ActivationObserver;

    impl ActivationObserver {
        #[unsafe(method(raffAppDidActivate:))]
        fn raff_app_did_activate(&self, notification: &NSNotification) {
            note_activation(activated_app(notification));
        }
    }

    unsafe impl NSObjectProtocol for ActivationObserver {}
);

/// The app named by a `NSWorkspaceDidActivateApplication` notification, falling
/// back to whoever is frontmost if the payload is not the expected shape.
fn activated_app(notification: &NSNotification) -> FrontApp {
    notification
        .userInfo()
        .and_then(|info| {
            // SAFETY: `NSWorkspaceApplicationKey` is an AppKit string constant,
            // valid for the lifetime of the process.
            let key: &NSString = unsafe { NSWorkspaceApplicationKey };
            let key: &AnyObject = key.as_ref();
            info.objectForKey(key)
        })
        .and_then(|value| value.downcast::<NSRunningApplication>().ok())
        .map(|app| FrontApp {
            pid: app.processIdentifier(),
            name: app
                .localizedName()
                .map(|s| s.to_string())
                .unwrap_or_default(),
            bundle_id: app
                .bundleIdentifier()
                .map(|s| s.to_string())
                .unwrap_or_default(),
        })
        .unwrap_or_else(frontmost_app)
}

/// Starts recording app activations, so a capture can ask who held the front
/// during the window a copy happened in rather than who holds it now.
///
/// Registration and delivery are main-thread work, so it hops there; calling
/// this more than once would register a second observer, so `start` is the only
/// caller.
pub fn start_activation_watch() {
    dispatch_to_main(|| {
        note_activation(frontmost_app());
        let observer = ActivationObserver::new();
        let center = NSWorkspace::sharedWorkspace().notificationCenter();
        // SAFETY: the observer responds to `raffAppDidActivate:` with the
        // (self, NSNotification *) signature AppKit posts, the name is an
        // AppKit constant, and the observer is leaked below so it outlives the
        // registration — NSNotificationCenter holds it unowned.
        unsafe {
            center.addObserver_selector_name_object(
                observer.as_ref(),
                sel!(raffAppDidActivate:),
                Some(NSWorkspaceDidActivateApplicationNotification),
                None,
            );
        }
        // One observer for the process lifetime; it is never removed, and the
        // notification center would dangle if it were dropped here.
        std::mem::forget(observer);
    });
}

impl ActivationObserver {
    fn new() -> Retained<Self> {
        let this = Self::alloc().set_ivars(());
        unsafe { msg_send![super(this), init] }
    }
}

/// Ordinary (Dock-visible) running apps, for the exclusion-list picker.
pub fn running_apps() -> Vec<(String, String)> {
    use objc2_app_kit::NSApplicationActivationPolicy;
    let ws = NSWorkspace::sharedWorkspace();
    let mut apps: Vec<(String, String)> = ws
        .runningApplications()
        .iter()
        .filter(|a| a.activationPolicy() == NSApplicationActivationPolicy::Regular)
        .filter_map(|a| {
            let name = a.localizedName()?.to_string();
            let bundle = a.bundleIdentifier()?.to_string();
            Some((name, bundle))
        })
        .collect();
    apps.sort();
    apps.dedup_by(|a, b| a.1 == b.1);
    apps
}

pub fn activate_app(pid: i32) {
    if pid <= 0 {
        return;
    }
    if let Some(app) = NSRunningApplication::runningApplicationWithProcessIdentifier(pid) {
        app.activateWithOptions(NSApplicationActivationOptions::ActivateIgnoringOtherApps);
    }
}

/// Synthesizes ⌘V in the frontmost app. Requires the Accessibility permission;
/// without it the events are silently dropped by macOS.
pub fn send_cmd_v() -> bool {
    if clipboard() == Clipboard::Inert {
        return false;
    }
    post_cmd_v()
}

/// Tests never press keys in another app: the press is only counted.
#[cfg(test)]
fn post_cmd_v() -> bool {
    test_clipboard::note_cmd_v();
    true
}

#[cfg(not(test))]
fn post_cmd_v() -> bool {
    use core_graphics::event::{CGEvent, CGEventFlags, CGEventTapLocation};
    use core_graphics::event_source::{CGEventSource, CGEventSourceStateID};

    const KEY_V: u16 = 9; // kVK_ANSI_V
    let Ok(source) = CGEventSource::new(CGEventSourceStateID::HIDSystemState) else {
        return false;
    };
    let (Ok(down), Ok(up)) = (
        CGEvent::new_keyboard_event(source.clone(), KEY_V, true),
        CGEvent::new_keyboard_event(source, KEY_V, false),
    ) else {
        return false;
    };
    down.set_flags(CGEventFlags::CGEventFlagCommand);
    up.set_flags(CGEventFlags::CGEventFlagCommand);
    down.post(CGEventTapLocation::HID);
    std::thread::sleep(std::time::Duration::from_millis(25));
    up.post(CGEventTapLocation::HID);
    true
}

/// The .app bundle containing the running executable, if any
/// (…/Raff.app/Contents/MacOS/raff → …/Raff.app). `None` in dev mode.
pub fn app_bundle_path() -> Option<std::path::PathBuf> {
    let exe = std::env::current_exe().ok()?;
    let bundle = exe.parent()?.parent()?.parent()?;
    (bundle.extension()? == "app").then(|| bundle.to_path_buf())
}

/// Relaunches the packaged app exactly once, after this process has fully
/// exited: a detached `/bin/sh` polls the pid (10 Hz, ~20 s cap) and only then
/// hands the bundle to LaunchServices. The wait is what makes the relaunch
/// safe with the single-instance plugin — launching while the old process
/// still holds the instance socket would make the new one forward its argv
/// and exit (i.e. no relaunch at all). `open` without `-n` never creates a
/// second process: if the cap is ever hit with the old instance alive, it
/// merely activates it — no duplicate tray, no relaunch loop. With
/// `reopen_settings`, `--settings` is forwarded so the fresh instance reopens
/// the settings surface.
pub fn spawn_relauncher(
    bundle: &std::path::Path,
    pid: u32,
    reopen_settings: bool,
) -> Result<(), String> {
    use std::process::{Command, Stdio};
    Command::new("/bin/sh")
        .arg("-c")
        .arg(relauncher_script(pid, reopen_settings))
        .arg(bundle)
        .stdin(Stdio::null())
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .spawn()
        .map(|_| ())
        .map_err(|err| format!("تعذّر جدولة إعادة تشغيل Raff: {err}"))
}

/// The relauncher's shell script. The bundle path travels as "$0", never
/// interpolated into the script; only the pid and fixed text are.
fn relauncher_script(pid: u32, reopen_settings: bool) -> String {
    let open = if reopen_settings {
        "exec /usr/bin/open \"$0\" --args --settings"
    } else {
        "exec /usr/bin/open \"$0\""
    };
    format!(
        "i=0; while kill -0 {pid} 2>/dev/null && [ $i -lt 200 ]; do sleep 0.1; i=$((i+1)); done; \
         {open}"
    )
}

